"""Caller-requested hang-up: call control, not model discretion.

Measured against the real demo prompt and tool set, Spark 1.3 never called the
hang-up tool when the caller said "please hang up now" (0/20 runs at low and
minimal effort); the model spoke a goodbye and stopped with ``finish_reason:
stop``. A smaller prompt called it 1/4 times, once with empty arguments (which
the executor denies). Meta also rejects a forced ``tool_choice`` with HTTP 400.

So the caller's words, not the model's tool choice, end the call. The reply is
still generated by the model and is what the caller hears; the pipeline then
closes the turn and arms the one hangup. The tool remains for endings the
*agent* decides (time up, off-track), where there is no caller request to read.

The phrase list is deliberately small and per-locale: a false positive ends a
live call, so only unambiguous end requests are named. Negations are checked
first ("please don't hang up").
"""

from __future__ import annotations

import re
from collections.abc import Mapping

