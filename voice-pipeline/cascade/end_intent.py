#: A caller who says one of these is asking to stay on the line.
_NEGATIONS: tuple[str, ...] = (
    "don't hang up",
    "do not hang up",
    "don't end",
    "do not end",
    "nicht auflegen",
    "legen sie nicht auf",
    "no cuelgues",
    "no cuelgue",
    "no termines",
    "no termine",
    "ne raccroche pas",
    "ne raccrochez pas",
    "ne termine pas",
    "não desligue",
    "nao desligue",
    "não encerre",
)

#: German separable verbs put words between the stem and the particle
#: ("legen Sie jetzt auf"), so the literal phrases above cannot catch them.
_END_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"\bleg\w*\b[^.?!]{0,24}\bauf\b"),
    re.compile(r"\bauf\w*\b[^.?!]{0,24}\bleg\w*\b"),
)
_NEGATION_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"\bleg\w*\b[^.?!]{0,24}\bnicht\b[^.?!]{0,24}\bauf\b"),
)

_WHITESPACE = re.compile(r"\s+")
_NON_WORD = re.compile(r"[^\w' ]+")


def normalize_final(text: str) -> str:
    """One comparable form: lowercase, curly apostrophes folded, punctuation out."""
    folded = text.replace("\u2019", "'").replace("\u2018", "'").lower()
    spaced = _NON_WORD.sub(" ", folded)
    return _WHITESPACE.sub(" ", spaced).strip()


def _phrase_pattern(phrase: str) -> re.Pattern[str]:
    # Word boundaries on both ends: "bye" must not match inside "by the way".
    return re.compile(rf"(?<!\w){re.escape(phrase)}(?!\w)")


def wants_to_end(text: str, locale: str = "en") -> bool:
    """Whether the caller's final turn asked to end the call.

    An unknown Locale falls back to English, the documented scaffolding
    exception. An empty final, or a negation of an end request, is not a
    request.
    """
    normalized = normalize_final(text or "")
    if not normalized:
        return False
    if any(_phrase_pattern(phrase).search(normalized) for phrase in _NEGATIONS):
        return False
    if any(pattern.search(normalized) for pattern in _NEGATION_PATTERNS):
        return False
    phrases = _END_PHRASES.get((locale or "en").lower(), _END_PHRASES["en"])
    return any(_phrase_pattern(phrase).search(normalized) for phrase in phrases) or any(
        pattern.search(normalized) for pattern in _END_PATTERNS
    )
