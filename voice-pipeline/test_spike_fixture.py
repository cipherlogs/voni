"""Ticket 09: the 20 s caller fixture for the latency spike.

The committed artifact is the sidecar — hash, provenance and the speech-end
sample. The WAV itself is gitignored working data regenerated byte-for-byte
from ``spike.fixture``. Collapse that distinction and the hash stops meaning
anything.
"""

import hashlib
import json
import tempfile
import unittest
from pathlib import Path

from spike import fixture


class CommittedSidecarTests(unittest.TestCase):
    def test_committed_sidecar_describes_the_regenerated_audio(self):
        sidecar = json.loads(fixture.SIDECAR_PATH.read_text())
        wav = fixture.build_wav()
        self.assertEqual(hashlib.sha256(wav).hexdigest(), sidecar["sha256"])
        self.assertEqual(fixture.read_wav(wav).frame_count, sidecar["frame_count"])

    def test_committed_sidecar_verifies_a_regenerated_wav(self):
        with tempfile.TemporaryDirectory() as tmp:
            wav_path = Path(tmp) / fixture.WAV_NAME
            wav_path.write_bytes(fixture.build_wav())
            verified = fixture.verify(wav_path, fixture.SIDECAR_PATH)
        committed = json.loads(fixture.SIDECAR_PATH.read_text())
        self.assertEqual(verified["sha256"], committed["sha256"])

    def test_sidecar_names_its_producer_and_reproduce_command(self):
        sidecar = json.loads(fixture.SIDECAR_PATH.read_text())
        provenance = sidecar["provenance"]
        self.assertTrue(provenance["source"])
        self.assertTrue(provenance["created"])
        self.assertIn("spike.fixture --write", provenance["reproduce"])
        self.assertEqual(sidecar["fixture"], "caller-20s")


class WavShapeTests(unittest.TestCase):
    def test_wav_is_twenty_seconds_mono_24k_16bit_pcm(self):
        facts = fixture.read_wav(fixture.build_wav())
        self.assertEqual(facts.sample_rate, 24_000)
        self.assertEqual(facts.channels, 1)
        self.assertEqual(facts.sample_width_bytes, 2)
        self.assertEqual(facts.frame_count, 480_000)
        self.assertAlmostEqual(facts.duration_s, 20.0)

    def test_speech_end_is_the_last_non_silent_sample(self):
        facts = fixture.read_wav(fixture.build_wav())
        samples = fixture.unpack_pcm(facts.pcm)
        end = fixture.last_speech_sample(facts.pcm)
        self.assertEqual(end, 297_600)
        self.assertNotEqual(samples[end], 0)
        self.assertTrue(all(sample == 0 for sample in samples[end + 1 :]))

    def test_there_is_leading_silence_before_the_speech_starts(self):
        facts = fixture.read_wav(fixture.build_wav())
        samples = fixture.unpack_pcm(facts.pcm)
        start = fixture.first_speech_sample(facts.pcm)
        self.assertGreater(start, 0)
        self.assertTrue(all(sample == 0 for sample in samples[:start]))

    def test_sidecar_records_speech_end_in_samples_and_ms(self):
        sidecar = fixture.build_sidecar(fixture.build_wav())
        self.assertEqual(sidecar["speech_end_sample"], 297_600)
        self.assertAlmostEqual(sidecar["speech_end_ms"], 12_400.0)
        self.assertEqual(sidecar["speech_start_sample"], 9_600)


class WriteTests(unittest.TestCase):
    def test_write_is_byte_stable(self):
        with tempfile.TemporaryDirectory() as tmp:
            first_audio = Path(tmp) / "a.wav"
            second_audio = Path(tmp) / "b.wav"
            first_sidecar = Path(tmp) / "a.json"
            second_sidecar = Path(tmp) / "b.json"
            fixture.write_fixture(first_audio, sidecar_path=first_sidecar)
            fixture.write_fixture(second_audio, sidecar_path=second_sidecar)
            self.assertEqual(first_audio.read_bytes(), second_audio.read_bytes())
            self.assertEqual(first_sidecar.read_text(), second_sidecar.read_text())

    def test_written_sidecar_verifies_its_own_audio(self):
        with tempfile.TemporaryDirectory() as tmp:
            wav_path = Path(tmp) / fixture.WAV_NAME
            sidecar_path = Path(tmp) / "caller-20s.json"
            fixture.write_fixture(wav_path, sidecar_path=sidecar_path)
            fixture.verify(wav_path, sidecar_path)


class DriftTests(unittest.TestCase):
    def test_tampered_audio_fails_by_hash(self):
        wav = bytearray(fixture.build_wav())
        wav[-1] ^= 0xFF
        with self.assertRaises(fixture.FixtureDrift) as caught:
            with tempfile.TemporaryDirectory() as tmp:
                wav_path = Path(tmp) / fixture.WAV_NAME
                wav_path.write_bytes(bytes(wav))
                fixture.verify(wav_path, fixture.SIDECAR_PATH)
        self.assertIn("sha256", str(caught.exception))

    def test_edited_speech_end_fails_by_field_name(self):
        sidecar = fixture.build_sidecar(fixture.build_wav())
        sidecar["speech_end_sample"] += 1
        with self.assertRaises(fixture.FixtureDrift) as caught:
            with tempfile.TemporaryDirectory() as tmp:
                tmp_path = Path(tmp)
                (tmp_path / "sidecar.json").write_text(json.dumps(sidecar))
                (tmp_path / fixture.WAV_NAME).write_bytes(fixture.build_wav())
                fixture.verify(tmp_path / fixture.WAV_NAME, tmp_path / "sidecar.json")
        self.assertIn("speech_end_sample", str(caught.exception))

    def test_edited_speech_end_ms_fails_by_field_name(self):
        sidecar = fixture.build_sidecar(fixture.build_wav())
        sidecar["speech_end_ms"] += 1.0
        with self.assertRaises(fixture.FixtureDrift) as caught:
            with tempfile.TemporaryDirectory() as tmp:
                tmp_path = Path(tmp)
                (tmp_path / "sidecar.json").write_text(json.dumps(sidecar))
                (tmp_path / fixture.WAV_NAME).write_bytes(fixture.build_wav())
                fixture.verify(tmp_path / fixture.WAV_NAME, tmp_path / "sidecar.json")
        self.assertIn("speech_end_ms", str(caught.exception))


class GitignoreTests(unittest.TestCase):
    def test_default_audio_path_is_gitignored(self):
        repo_root = Path(fixture.__file__).resolve().parents[2]
        gitignore = (repo_root / ".gitignore").read_text().splitlines()
        patterns = [line.strip() for line in gitignore]
        audio_path = fixture.default_audio_path()
        self.assertIn(fixture.AUDIO_DIRNAME, audio_path.parts)
        self.assertIn(f"voice-pipeline/{fixture.AUDIO_DIRNAME}/", patterns)


if __name__ == "__main__":
    unittest.main()
